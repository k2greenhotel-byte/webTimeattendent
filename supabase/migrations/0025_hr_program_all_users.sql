-- เปิดโปรแกรม HR (ขอลา/ขอเบิกเงินเดือน) ให้พนักงานทุกคนเหมือนระบบลงเวลา (ATT)
--
-- 0024 ให้สิทธิ์เข้าโปรแกรมนี้เฉพาะ admin/assistant_admin ไว้ก่อน (ค่าตั้งต้นตอนสร้างโปรแกรมใหม่)
-- ผู้ใช้ต้องการให้พนักงานทุกคนแจ้งลา/ขอเบิกเงินได้เองเหมือนระบบลงเวลาเข้า-ออกงาน
-- จึงเปิดประตูเข้าโปรแกรม (user_programs) ให้ทุกคน แบบเดียวกับที่ 0009 เปิด ATT/MKT ให้ทุกคน
--
-- ชั้นที่สอง (level_menu_permissions ใน 0024) ควบคุมอยู่แล้วว่าเข้าไปแล้วทำอะไรได้:
--   - ทุกระดับ    : เข้าเมนูแจ้งลา/แจ้งเบิกและดูของตัวเองได้ (HR_LEAVE_NEW/MINE, HR_ADV_NEW/MINE)
--   - supervisor+ : เห็นหน้าอนุมัติเพิ่ม (HR_LEAVE_APPROVE, HR_ADV_APPROVE)
--   - admin/ผู้ช่วย: ตั้งค่าประเภทการลาได้เพิ่ม (HR_TYPES)
-- migration นี้แก้แค่ชั้นแรก ไม่แตะชั้นที่สอง
--
-- ไม่ลบสิทธิ์ของใคร และรันซ้ำได้ (on conflict do nothing)
-- แอดมินถอดสิทธิ์เป็นรายคนได้ภายหลังที่ /core/program-users
-- รันต่อจาก 0024
-- ============================================================

insert into public.user_programs (user_id, program_id)
select e.id, p.id
from public.employees e
cross join public.programs p
where p.code = 'HR'
on conflict do nothing;
