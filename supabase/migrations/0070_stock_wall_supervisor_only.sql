-- migration 0069 เปิดให้ทุกระดับเห็น ซึ่งหลุดนโยบายที่ใช้กับจอ War Room
-- ทุกจอของทั้งระบบ (admin / ผู้ช่วยดูแล / หัวหน้างาน เท่านั้น) — เป็นรูปแบบ
-- เดียวกับที่ migration 0030 เคยพลาดไว้กับ DB2_WALL แล้วแก้ไปใน 0049
--
-- ใช้ตัวกรอง %_WALL เหมือน 0049 เพื่อให้จอที่เพิ่มมาใหม่ทุกจอถูกจัดให้ตรง
-- นโยบายไปพร้อมกัน ไม่ต้องไล่แก้ทีละรหัสอีก
