-- ระบบอนุมัติกลาง: วงเงินที่ "ไม่ต้องขออนุมัติ" ต่อประเภทเรื่อง
--
-- โจทย์: ใบขอเบิกเงินเดือนที่ยอดไม่เกิน 3,000 บาท ไม่ต้องรอผู้มีอำนาจ ให้ผ่านเลย
-- ยอดที่มากกว่านั้นถึงต้องเข้ากล่องรออนุมัติ — ตัวเลข 3,000 ผู้ดูแลแก้ได้เองจากหน้าตั้งค่าอำนาจอนุมัติ
-- เก็บไว้ที่ apv_types (เป็นคุณสมบัติของประเภทเรื่อง) เผื่อเรื่องอื่นอยากใช้แบบเดียวกันในอนาคต
--   null = ต้องขออนุมัติทุกใบ (ค่าเริ่มต้นของทุกเรื่อง)

alter table public.apv_types
  add column if not exists auto_approve_limit numeric(12, 2);

comment on column public.apv_types.auto_approve_limit is
  'ยอดที่ไม่เกินนี้ระบบอนุมัติให้เองทันที ไม่ต้องรอผู้มีอำนาจ (null = ต้องขออนุมัติทุกใบ)';

-- ค่าตั้งต้นตามที่ผู้ใช้กำหนด: เบิกเงินเดือน ≤ 3,000 บาท ไม่ต้องขออนุมัติ
-- ใส่เฉพาะตอนยังไม่เคยตั้ง จะได้ไม่ทับค่าที่ผู้ดูแลแก้ไว้แล้วเวลารัน migration ซ้ำ
update public.apv_types
   set auto_approve_limit = 3000
 where code = 'SALARY_ADV'
   and auto_approve_limit is null;
