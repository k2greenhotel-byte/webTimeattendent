-- ============================================================
-- แก้รหัสบริษัทรถที่พิมพ์ผิด: 'ํYM' → 'YM'
--
-- รหัสเดิมมีนิคหิต (U+0E4D) ติดมาหน้าตัวอักษร มองด้วยตาแทบไม่เห็น
-- แต่ทำให้ค้นหาด้วยคำว่า YM ไม่เจอ และเรียงลำดับผิดตำแหน่ง
-- เอกสารที่อ้างถึงบริษัทนี้ผูกด้วย id ไม่ใช่รหัส จึงไม่กระทบข้อมูลเดิม
--
-- ปลอดภัยถ้ารันซ้ำ (ไม่มีแถวให้แก้ก็ไม่ทำอะไร) และไม่แตะถ้ามีรหัส YM อยู่แล้ว
-- ============================================================

update public.mc_vendors
set code = 'YM'
where code = 'ํYM'
  and not exists (select 1 from public.mc_vendors v where v.code = 'YM');
